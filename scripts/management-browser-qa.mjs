  const admin=await context.newPage();admin.on('pageerror',e=>errors.push(e.message));
  await admin.goto(base+'/admin.html');
  await admin.getByLabel('管理密钥').fill(readFileSync(join(directory,'admin-key.txt'),'utf8').trim());
  await admin.getByRole('button',{name:'进入管理后台',exact:true}).click();
  await admin.getByRole('heading',{name:'营运总览',exact:true}).waitFor();
  assert.equal((await api('auth/session')).user.id,user.id);
  await admin.getByRole('button',{name:'用户与会员',exact:true}).click();
  await admin.getByRole('button',{name:'管理',exact:true}).click();
  await admin.getByLabel('操作原因').fill('浏览器联动测试');
  await admin.getByRole('button',{name:'开通／延长会员',exact:true}).click();
  await admin.getByRole('button',{name:'确认保存',exact:true}).click();
  await admin.getByRole('status').filter({hasText:'会员资料已保存'}).waitFor();
  await student.bringToFront();await student.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await student.locator('.membership-status').filter({hasText:'会员至'}).waitFor({timeout:25000});
  await student.getByRole('button',{name:'2. 展开考评局官方解答',exact:true}).click();
  await student.getByRole('button',{name:'3. 展开详细思路解答',exact:true}).click();
  await student.locator('.reasoning-content').waitFor();
  assert.ok(await student.locator('.related-panel button').count());
  const out=resolve('../tmp/management-qa');mkdirSync(out,{recursive:true});
  await admin.screenshot({path:join(out,'members.png'),fullPage:true});
  await admin.getByLabel('操作原因').fill('测试取消');
  await admin.getByRole('button',{name:'取消会员',exact:true}).click();
  await admin.getByRole('button',{name:'确认保存',exact:true}).click();
  await admin.getByRole('status').filter({hasText:'会员资料已保存'}).waitFor();
