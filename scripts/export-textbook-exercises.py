"""Export the existing bilingual exercises as portable, ordered JSON archives."""
import hashlib
import json
import pathlib
import re
import shutil

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/textbook-exercises'
OUTPUT = ROOT.parent / 'output/课本习题JSON'
PREFIX = 'assets/textbook-exercises/media/'


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def natural(value):
    return tuple((1, int(s)) if s.isdigit() else (0, s) for s in re.split(r'(\d+)', value))


for lang, label in [('chn', '中文版'), ('eng', '英文版')]:
    target = OUTPUT / label / '课本习题'
    (target / 'media').mkdir(parents=True, exist_ok=True)
    index = json.loads((SOURCE / f'index-{lang}.json').read_text(encoding='utf-8'))
    chapters = [chapter for book in index['books'] for chapter in book['chapters']]
    metadata = {q['id']: q for q in index['questions']}
    ordered, media, chapter_files = [], set(), []

    def portable(value):
        if isinstance(value, str):
            media.update(re.findall(re.escape(PREFIX) + r'([^\s\"\'<>]+)', value))
            return value.replace(PREFIX, 'media/')
        if isinstance(value, list):
            return [portable(v) for v in value]
        if isinstance(value, dict):
            return {k: portable(v) for k, v in value.items()}
        return value

    for chapter in chapters:
        filename = chapter['id'] + '.json'
        raw = json.loads((SOURCE / lang / filename).read_text(encoding='utf-8'))
        records = {}
        for key in sorted(raw, key=natural):
            q = portable(raw[key])
            assert q['id'] == key and q['chapter'] == chapter['id']
            # Preserve the existing catalog associations alongside original content.
            for field in ('knowledge', 'section', 'preview'):
                if field in metadata[key]:
                    q[field] = metadata[key][field]
            records[key] = q
            ordered.append(q)
        assert len(records) == chapter['count']
        write_json(target / filename, records)
        chapter_files.append(filename)
    assert len(ordered) == len(metadata) == len({q['id'] for q in ordered})
    assert set(metadata) == {q['id'] for q in ordered}
    for filename in sorted(media):
        assert pathlib.Path(filename).name == filename
        shutil.copy2(SOURCE / 'media' / filename, target / 'media' / filename)
    index['questions'] = [metadata[q['id']] for q in ordered]
    write_json(target / 'index.json', index)
    write_json(target / 'exercises.json', ordered)
    manifest = {
        'language': lang, 'chapter_count': len(chapters), 'question_count': len(ordered),
        'media_count': len(media), 'chapter_files': chapter_files,
        'combined_file': 'exercises.json',
        'content_format': 'HTML and MathML text; image paths are relative to this folder.',
        'ordering': 'Book and chapter order from the website index, then natural question number order.',
        'empty_answer_ids': [q['id'] for q in ordered if not q.get('answer', '').strip()],
        'empty_reasoning_count': sum(not q.get('reasoning', '').strip() for q in ordered),
        'note': 'Original questions and answers with source-checked DDPhysics teaching supplements. Structured worked answers may be stored in answer rather than reasoning. No QDNA is generated by this export.',
        'empty_mc_reasoning_ids': [q['id'] for q in ordered if q.get('kind') == 'multiple-choice' and not q.get('reasoning', '').strip()],
        'source_files_sha256': {
            str(p.relative_to(SOURCE)).replace('\\', '/'): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in [SOURCE / f'index-{lang}.json'] + [SOURCE / lang / f for f in chapter_files]
        },
    }
    write_json(target / 'manifest.json', manifest)
    # Reopen every exported JSON and verify all referenced images exist.
    for file in target.glob('*.json'):
        json.loads(file.read_text(encoding='utf-8'))
    assert all((target / 'media' / f).is_file() for f in media)
    print(json.dumps({k: manifest[k] for k in ('language', 'chapter_count', 'question_count', 'media_count', 'empty_answer_ids', 'empty_reasoning_count')}, ensure_ascii=False))
