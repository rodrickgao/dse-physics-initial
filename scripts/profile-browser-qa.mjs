import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import sharp from 'sharp';
import ExcelJS from 'exceljs';
import { PHYSICISTS } from '../src/lib/avatar-catalog.js';
const base = process.env.QA_BASE || 'http://127.0.0.1:5178';
const out = '../tmp/profile-browser-qa/screenshots'; fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
const page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
const email = `profile-${Date.now()}@example.com`;
try {
  await page.goto(base);
  await page.getByLabel('電郵地址').fill(email);
  await page.getByRole('button', { name: '取得驗證碼', exact: true }).click();
  const code = await page.locator('.local-code strong').innerText();
  await page.locator('input[autocomplete="one-time-code"]').fill(code);
  await page.getByRole('button', { name: '註冊 / 登入', exact: true }).click();
  await page.getByRole('heading', { name: '建立你的物理學習檔案' }).waitFor();
  assert.equal(await page.getByRole('button', { name: '完成註冊，開始學習' }).isDisabled(), true);
  await page.locator('#profile-nickname').fill('星際同學');
    await page.getByLabel('新密碼', { exact: true }).fill('Study-pass-123');
    await page.getByLabel('確認新密碼', { exact: true }).fill('Study-pass-123');
  await page.getByRole('radio', { name: '中五', exact: true }).check();
  await page.getByRole('radio', { name: '5**', exact: true }).check();
  for (const person of PHYSICISTS) {
    await page.getByRole('button', { name: person.name, exact: true }).click();
    assert.equal(await page.locator('.avatar-options img').count(), 5);
    await page.locator('.avatar-options img').evaluateAll(images => Promise.all(images.map(img => img.decode())));
  }
  await page.getByRole('button', { name: '牛頓', exact: true }).click();
  await page.getByRole('button', { name: '牛頓 · 閱讀', exact: true }).click();
  await page.locator('.avatar-options img').first().evaluate(img => img.decode());
  await page.screenshot({ path: `${out}/create-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: `${out}/create-mobile.png`, fullPage: true });
  await page.getByRole('button', { name: '完成註冊，開始學習' }).click();
  await page.locator('.account-bar').waitFor();
  assert.match(await page.locator('.account-bar').innerText(), /星際同學/);
  await page.reload(); await page.locator('.account-avatar').waitFor();
  const state = await (await context.request.get(`${base}/api/auth/session`)).json();
  assert.equal(state.user.grade, '中五'); assert.equal(state.user.target, '5**'); assert.equal(state.user.avatar, 'newton-read');
  await page.getByRole('button', { name: '個人資料', exact: true }).click();
  await page.getByRole('button', { name: '更換頭像', exact: true }).click();
  await page.getByRole('button', { name: '上傳我的圖片', exact: true }).click();
  await page.getByLabel('上傳自訂頭像').setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('bad') });
  await page.getByRole('alert').waitFor();
  const png = await sharp({ create: { width: 420, height: 300, channels: 3, background: '#b8cdea' } }).png().toBuffer();
  await page.getByLabel('上傳自訂頭像').setInputFiles({ name: 'custom.png', mimeType: 'image/png', buffer: png });
  await page.locator('.upload-preview img').waitFor();
  await page.getByRole('button', { name: '儲存個人資料', exact: true }).click();
  await page.locator('.account-bar').waitFor();
  const custom = await (await context.request.get(`${base}/api/auth/session`)).json();
  assert.equal(custom.user.avatar, 'upload');
  const response = await context.request.get(base + custom.user.avatarUrl);
  assert.equal(response.status(), 200); assert.equal(response.headers()['content-type'], 'image/webp');
  const metadata = await sharp(await response.body()).metadata(); assert.equal(metadata.width, 384);
  await page.reload(); await page.locator('.account-avatar').waitFor();
  await page.locator('.account-avatar').evaluate(img => img.decode());
  await page.getByRole('button', { name: '登出', exact: true }).click();
  assert.equal((await context.request.get(base + custom.user.avatarUrl)).status(), 401);
  await page.getByRole('button', { name: '開發者入口', exact: true }).click();
  await page.getByLabel('開發者密鑰').fill(fs.readFileSync('../tmp/profile-browser-qa/admin-key.txt','utf8').trim());
  await page.getByRole('button', { name: '進入統計後台', exact: true }).click();
  await page.getByLabel('搜尋學生電郵').fill('星際同學');
  await page.locator('.admin-student-identity').first().waitFor();
  const result = await (await context.request.get(`${base}/api/admin/export`)).json();
  const book = new ExcelJS.Workbook(); await book.xlsx.load(Buffer.from(result.base64, 'base64'));
  const text = JSON.stringify(book.getWorksheet('學生摘要').getSheetValues());
  assert.ok(text.includes('星際同學') && text.includes('中五') && text.includes('5**') && text.includes('upload'));
  assert.deepEqual(errors, []);
  console.log('PASS: complete registration, presets, custom upload, invalid images, mobile layout, reload, avatar privacy, developer view and profile export.');
} finally { await browser.close(); }

